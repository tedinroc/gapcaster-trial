def apply(p: Path, s: str, replacements: list) -> str:
    for old, new, n in replacements:
        got = s.count(old)
        if got not in (n if isinstance(n, tuple) else (n,)):
            sys.exit(f"{p}: expected {n} of {old[:60]!r}, found {got}")
        s = s.replace(old, new)
    return s


for d in ("A-1", "A-2", "B-1", "B-2"):
    p = SITE / "review" / d / "review_pilot.html"
    s = p.read_text(encoding="utf-8")
    done = []
    if MARK not in s:
        s = apply(p, s, REPLACEMENTS)
        if not s.rstrip().endswith(TAIL_OLD):
            sys.exit(f"{p}: unexpected end of file")
        s = s.rstrip()[: -len(TAIL_OLD)] + TAIL_NEW + "\n"
        done.append("送出")
    if CSP_MARK not in s:
        s = apply(p, s, REPLACEMENTS_CSP)
        done.append("CSP")
    if done:
        p.write_text(s, encoding="utf-8")
        print(f"patched {p.relative_to(SITE)}: {', '.join(done)}")
    else:
        print(f"{p.relative_to(SITE)}: already patched")
